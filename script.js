  const CRC_TABLE = (() => {
    const table = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) {
        c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
      }
      table[n] = c >>> 0;
    }
    return table;
  })();
  function crc32(bytes) {
    let c = 0xFFFFFFFF;
    for (let i = 0; i < bytes.length; i++) {
      c = CRC_TABLE[(c ^ bytes[i]) & 0xFF] ^ (c >>> 8);
    }
    return (c ^ 0xFFFFFFFF) >>> 0;
  }
  function u32(n) {
    return new Uint8Array([(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255]);
  }
  function concatBytes(arrays) {
    let len = 0;
    arrays.forEach(a => len += a.length);
    const out = new Uint8Array(len);
    let off = 0;
    arrays.forEach(a => { out.set(a, off); off += a.length; });
    return out;
  }
  // Insert a pHYs chunk (pixels-per-meter, both axes) right after IHDR.
  async function injectDpi(blob, dpi) {
    const buf = new Uint8Array(await blob.arrayBuffer());
    const sig = buf.slice(0, 8);
    let pos = 8;
    const ihdrLen = (buf[8] << 24 | buf[9] << 16 | buf[10] << 8 | buf[11]) >>> 0;
    const ihdrChunk = buf.slice(8, 8 + 8 + ihdrLen + 4); // length+type+data+crc
    const rest = buf.slice(8 + 8 + ihdrLen + 4);

    const ppm = Math.round(dpi / 0.0254); // pixels per meter
    const physData = concatBytes([u32(ppm), u32(ppm), new Uint8Array([1])]); // unit=1 (meter)
    const typeBytes = new TextEncoder().encode('pHYs');
    const crc = crc32(concatBytes([typeBytes, physData]));
    const physChunk = concatBytes([u32(physData.length), typeBytes, physData, u32(crc)]);

    return new Blob([sig, ihdrChunk, physChunk, rest], { type: 'image/png' });
  }

